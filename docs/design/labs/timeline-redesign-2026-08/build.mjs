/* Assemble master.html from the part files.
 *
 *   node docs/design/labs/timeline-redesign-2026-08/build.mjs
 *
 * The parts are the editable source; master.html is generated and should
 * never be hand-edited. Two reasons this exists rather than a stack of
 * <link> tags:
 *
 *   1. The Elevation Log builds its palette receipt by reading the
 *      MASTER'S OWN <style> block. A master whose CSS lives in linked
 *      files has an empty receipt, and a receipt that cannot see the file
 *      it describes is worse than no receipt.
 *   2. The compiled console inlines fonts by finding url(./fonts/*.woff2)
 *      in the same CSS text, so the whole stylesheet has to travel as one
 *      body of text anyway.
 *
 * The JS parts stay separate: build-console.mjs inlines them itself from
 * elevate.config.json's console.inline list.
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import QRCode from "qrcode";

const LAB = path.dirname(fileURLToPath(import.meta.url));
/* The lock. Direction B is the locked direction; a.css / render-a.js and
 * c.css / render-c.js stay in the lab as the record of the exploration
 * and are no longer built into the master. Re-pointing the loop at
 * another direction is this one line plus a room definition. */
const CSS = ["fonts.css", "shell.css", "b.css"];
const JS = ["fixture.js", "render-core.js", "render-b.js"];

/* The printed sheet is handed to the venue, the celebrant and the day's
 * helpers on the morning - the people who do NOT already hold the link,
 * because the couple and the families got the card in a message. Its
 * only route back was a 76-character URL ending in a 43-character
 * case-sensitive token, set in mono and broken across three lines: an
 * instruction nobody can follow off paper. The code is generated HERE,
 * at build time, from the fixture's own token, so the master stays one
 * self-contained file with no external asset and no runtime library. */
const fixture = await readFile(path.join(LAB, "fixture.js"), "utf8");
const token = (fixture.match(/var TOKEN = "([^"]+)"/) || [])[1];
if (!token) throw new Error("build.mjs: no TOKEN in fixture.js — the sheet's scannable route cannot be generated");
const shareUrl = "https://timeline.signalstudio.ie/s/" + token;
const qr = await QRCode.toString(shareUrl, {
  type: "svg",
  errorCorrectionLevel: "M",
  margin: 0,
  color: { dark: "#111111", light: "#ffffff" },
})
  /* The module path is drawn with stroke and no fill, so it inherits
     the SVG default of black - one hue off the three the palette lock
     permits, in a file whose whole point is that there are three. */
  .then((svg) => svg.replace("<path stroke=", '<path fill="none" stroke='));

const css = [];
for (const file of CSS) {
  css.push(`/* ══ ${file} ══════════════════════════════════════════ */`);
  css.push((await readFile(path.join(LAB, file), "utf8")).trim());
}

const page = `<!doctype html>
<html lang="en-IE">
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Signal Timeline · design master</title>
<!-- GENERATED by build.mjs from ${CSS.join(", ")}. Do not hand-edit. -->
<style>
${css.join("\n\n")}
</style>
<body data-state="owner-flight" data-v="paper" data-ground="paper" data-past="folded" data-accent="structure">
<div id="tl"></div>
<script>window.__TLQR = ${JSON.stringify({ url: shareUrl, svg: qr })};</script>
${JS.map((f) => `<script src="./${f}"></script>`).join("\n")}
<script>
/* The toolchain contract, and the whole of it: this file answers ?state=
   and ?v=, plus the two named decisions. shots.mjs, audit.mjs and the
   compiled console drive it through those parameters and nothing else. */
(function () {
  var q = new URLSearchParams(location.search);
  var root = document.getElementById("deck") || document.body;
  /* ?v= names a ROOM, and a room is a preset of the named decisions. It
     applies the whole preset first so that shots.mjs --v=paper and
     audit.mjs --v=paper grade the room the console shows, not the
     default decisions with a different label on them. Explicit
     parameters then override, so ?v=paper&ground=ink is still reachable. */
  var room = q.get("v");
  var presets = window.__elevate.presets;
  if (room && presets[room]) {
    Object.keys(presets[room]).forEach(function (key) {
      root.setAttribute("data-" + key, presets[room][key]);
    });
  }
  ["state", "v", "ground", "past", "accent"].forEach(function (key) {
    var value = q.get(key);
    if (value) root.setAttribute("data-" + key, value);
  });
  window.__TLCORE.mount();
})();
</script>
</body>
`;

await writeFile(path.join(LAB, "master.html"), page, "utf8");
process.stdout.write(`master.html · ${CSS.length} stylesheets · ${JS.length} scripts · ${Math.round(page.length / 1024)} KB\n`);
